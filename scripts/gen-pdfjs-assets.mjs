/**
 * Inlines the installed pdfjs-dist runtime assets into a generated TypeScript
 * module, so the browser half carries its own PDF engine.
 *
 * The alternative — serving the worker and font files from this plugin's host
 * routes — would work, but adding a host route only takes effect when the DSH
 * host process reloads the plugin, which no rebuild of ours can trigger.
 * Inlining keeps one rebuild + page refresh as the whole deployment step, which
 * is also what the shipped document preview does.
 *
 * Run by `pnpm build` before `tsc`; the output is generated, not committed.
 */
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = join(root, 'node_modules', 'pdfjs-dist')
const outDir = join(root, 'src', 'client', 'generated')
const outFile = join(outDir, 'pdfjs-assets.ts')

/** Directory name under pdfjs-dist → the `kind` its BinaryDataFactory requests. */
const ASSET_KINDS = {
  standard_fonts: 'standardFontDataUrl',
  cmaps: 'cMapUrl',
}

function readBase64Map(directory) {
  const map = {}
  for (const name of readdirSync(directory)) {
    const full = join(directory, name)
    if (!statSync(full).isFile()) continue
    map[name] = readFileSync(full).toString('base64')
  }
  return map
}

/** A JS string literal for arbitrary text: JSON escaping plus the line separators JS also treats as newlines. */
function literal(text) {
  return JSON.stringify(text).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029')
}

const worker = readFileSync(join(pkg, 'build', 'pdf.worker.min.mjs'), 'utf8')
const assets = {}
let total = 0
for (const [directory, kind] of Object.entries(ASSET_KINDS)) {
  const map = readBase64Map(join(pkg, directory))
  assets[kind] = map
  for (const value of Object.values(map)) total += value.length
}

const header = `/**
 * Generated by scripts/gen-pdfjs-assets.mjs — do not edit, not committed.
 *
 * PDF.js ${JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')).version} runtime assets:
 * the worker source and the base64 resource tables its BinaryDataFactory reads.
 */`

const body = [
  header,
  '',
  '/** The PDF.js worker, started from a Blob URL so no file has to be served. */',
  `export const PDF_WORKER_SOURCE = ${literal(worker)}`,
  '',
  '/** Base64 resources by the kind PDF.js requests them under. */',
  'export const PDF_ASSETS: Readonly<Record<string, Readonly<Record<string, string>>>> = {',
  ...Object.entries(assets).map(([kind, map]) => {
    const entries = Object.entries(map).map(([name, value]) => `    ${literal(name)}: ${literal(value)},`)
    return `  ${literal(kind)}: {\n${entries.join('\n')}\n  },`
  }),
  '}',
  '',
].join('\n')

mkdirSync(outDir, { recursive: true })
writeFileSync(outFile, body)
console.log(`[pdfjs-assets] worker ${worker.length} B, resources ${total} B base64 → src/client/generated/pdfjs-assets.ts`)
